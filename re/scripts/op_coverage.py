"""Build the HLO->MPS op coverage table for the jax-metal plugin.

Inputs (all produced earlier in re/work, see re/FINDINGS.md):
  drr-root-ops.tsv     GeneratedConvertN -> "mps.target,...,mhlo.source" from pattern constructors
  mps-converters.tsv   hand-written converter class -> source op from matchAndRewrite signatures
  vhlo-ops-0.19.4.txt  VHLO ops at StableHLO 271e8634 (0.19.4), the plugin's pinned commit

    python3 -I re/scripts/op_coverage.py re/work re/findings/vhlo-ops-0.19.4.txt \
        re/findings/mps-op-coverage.md
"""

import os
import re
import sys

# From the REA decompilation of compileMlirHLOToMPS and the functions it calls.
PIPELINE = """## Compilation pipeline

Decompiled with REA (`re/findings/rea-compileMlirHLOToMPS.c`, `rea-populatePreLegalization.c`
at `0x1937c`, `rea-populatePassManager.c`; evidence in
`re/evidence/phase1-op-pipeline-bundle.json`). `compileMlirHLOToMPS` runs:

1. `mhlo::createStablehloLegalizeToHloPass` (StableHLO -> MHLO)
2. `createInlinerPass` (func-call inlining; does not expand `composite` ops)
3. `DecomposeChloToHLOPass` (Apple)
4. `mhlo::createLegalizeGeneralDotPass`, `createHloCanonicalizeGatherPass`,
   `createHloCanonicalizeScatterPass`, `createFlattenTuplePass`, canonicalizer
5. `LegalizeControlFlowPass` (Apple)
6. `ConvertHLOToMPSPass` (the patterns below), `RemoveZeroDimPass` (Apple), canonicalizer

No pass expands `stablehlo.composite`/`mhlo.composite`, so CHLO ops that current XLA serializes as
composites (`ChloPreserveHighLevelOpsPass`) fail to legalize even when an MPS pattern exists for the
underlying CHLO op. The shim package works around this with METAL lowering rules.

"""


def snake(class_name):
    name = re.sub(r"Op$", "", class_name)
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def read_lines(path):
    with open(path, encoding="utf-8") as handle:
        return handle.read().splitlines()


def main(work, vhlo_ops_path, out_path):
    patterns = {}  # "mhlo.add" -> list of descriptions

    for line in read_lines(os.path.join(work, "drr-root-ops.tsv")):
        pattern, _, names = line.split("\t")
        ops = names.split(",") if names else []
        sources = [op for op in ops if op.split(".")[0] in ("mhlo", "chlo")]
        targets = [op for op in ops if op.startswith("mps.")]
        for source in sources:
            target = ", ".join(targets) if targets else "several mps ops"
            patterns.setdefault(source, []).append(f"{pattern} (DRR) -> {target}")

    for line in read_lines(os.path.join(work, "mps-converters.tsv")):
        fields = line.split("\t")
        if len(fields) != 2:  # mps -> scf/tensor deserialization patterns
            continue
        converter, source = fields
        match = re.fullmatch(r"mlir::(mhlo|chlo)::(\w+)", source)
        if match:
            name = f"{match.group(1)}.{snake(match.group(2))}"
            patterns.setdefault(name, []).append(converter)

    vhlo = sorted({re.sub(r"_v\d+$", "", line.strip()[len("vhlo."):])
                   for line in read_lines(vhlo_ops_path) if line.strip()})
    # StableHLO ops map to MHLO ops of the same name.
    lowered = {name.split(".", 1)[1] for name in patterns if name.startswith("mhlo.")}
    structural = {"return", "func", "call", "tuple", "get_tuple_element", "after_all",
                  "create_token", "optimization_barrier"}
    missing = [op for op in vhlo if op not in lowered and op not in structural]

    with open(out_path, "w", encoding="utf-8") as out:
        out.write("# HLO -> MPS op coverage of jax-metal 0.1.1\n\n")
        out.write("Generated by `re/scripts/op_coverage.py` from the plugin's own patterns: "
                  "52 TableGen (DRR) patterns `mlir::mps::GeneratedConvertN` (source and target "
                  "op names read from each pattern's constructor) and the hand-written "
                  "`mlir::mps::(anonymous namespace)::*Converter` classes (source op from each "
                  "`matchAndRewrite` signature). Apple's lowering works on MHLO/CHLO; "
                  "StableHLO is legalized to MHLO first.\n\n")
        out.write(PIPELINE)
        out.write(f"## Ops with an MPS lowering pattern ({len(patterns)})\n\n")
        out.write("| Source op | Pattern(s) |\n|---|---|\n")
        for name in sorted(patterns):
            out.write(f"| `{name}` | {'; '.join(patterns[name])} |\n")
        out.write(f"\n## StableHLO 0.19.4 ops with no direct MPS pattern ({len(missing)})\n\n")
        out.write("These fail in the plugin unless an earlier pass in its pipeline rewrites them "
                  "into covered ops (see the empirical results in "
                  "`re/findings/jax-op-probe.md`).\n\n")
        out.write(", ".join(f"`{op}`" for op in missing) + "\n")
    print(f"{len(patterns)} source ops with patterns; {len(missing)} StableHLO ops without")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3])
