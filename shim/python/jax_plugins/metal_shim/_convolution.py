"""Convolution layouts for Apple's MPS converter."""

from jax import lax
from jax._src.interpreters import mlir
from jax._src.lax import convolution

from jax_plugins.metal_shim import _complex


def register(register_rule):
    primitive = convolution.conv_general_dilated_p
    default = _complex.current_rule(primitive)

    def rule(ctx, lhs, rhs, *, dimension_numbers, **params):
        dilation = params["lhs_dilation"]
        if any(d != 1 for d in dilation):
            def explicit_dilation(x, w):
                padding = [(0, 0, 0)] * x.ndim
                for axis, factor in zip(dimension_numbers.lhs_spec[2:], dilation):
                    padding[axis] = (0, 0, factor - 1)
                x = lax.pad(x, lax.full((), 0, x.dtype), padding)
                return primitive.bind(x, w, dimension_numbers=dimension_numbers,
                                      **dict(params, lhs_dilation=(1,) * len(dilation)))
            return mlir.lower_fun(explicit_dilation, multiple_results=False)(ctx, lhs, rhs)
        permutation = dimension_numbers.rhs_spec
        canonical = tuple(range(len(permutation)))
        if permutation == canonical:
            return default(ctx, lhs, rhs, dimension_numbers=dimension_numbers, **params)
        # The converter treats IO-spatial kernels as transpose convolutions,
        # misinterpreting stride in ordinary convolutions generated by autodiff.
        # A physical transpose to OI-spatial has exactly the same semantics.
        aval = ctx.avals_in[1]
        transposed_aval = aval.update(shape=tuple(aval.shape[d] for d in permutation))
        rhs, = mlir.lower_fun(lambda x: lax.transpose(x, permutation), multiple_results=False)(
            ctx.replace(avals_in=[aval], avals_out=[transposed_aval], tokens_out=None), rhs)
        dnums = dimension_numbers._replace(rhs_spec=canonical)
        return default(ctx.replace(avals_in=[ctx.avals_in[0], transposed_aval], tokens_out=None),
                       lhs, rhs, dimension_numbers=dnums, **params)

    register_rule(primitive, rule)
